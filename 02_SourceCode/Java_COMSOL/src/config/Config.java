package config;

public class Config {
    private ModelConfig modelConfig;
    private PathConfig pathConfig;

    public ModelConfig getModelConfig() { return modelConfig; }
    public void setModelConfig(ModelConfig modelConfig) { this.modelConfig = modelConfig; }

    public PathConfig getPathConfig() { return pathConfig; }
    public void setPathConfig(PathConfig pathConfig) { this.pathConfig = pathConfig; }
}