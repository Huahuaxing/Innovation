fig2 = figure( ...
    'Color',[1 1 1], ...
    'Position',[100 100 1200 800]);

tiledlayout(2,2, ...
    'TileSpacing','compact', ...
    'Padding','compact');

groups = 1:cycle;

ellipseParams = { ...
    params_ellipse(:,1), ...
    params_ellipse(:,2), ...
    params_ellipse(:,3), ...
    params_ellipse(:,4)};

nonellipseParams = { ...
    params_nonellipse(:,1), ...
    params_nonellipse(:,2), ...
    params_nonellipse(:,3), ...
    params_nonellipse(:,4)};

yLabels = { ...
    'A value', ...
    'K value', ...
    'B value', ...
    'D value'};

% ===================== 标准线 =====================
standardValues = [2120, 0, 340, NaN];

for i = 1:4

    nexttile;

    hold on;

    plot(groups, ellipseParams{i}, '-sk', ...
        'LineWidth',2, ...
        'MarkerSize',8, ...
        'MarkerFaceColor','w');

    plot(groups, nonellipseParams{i}, '-^k', ...
        'LineWidth',2, ...
        'MarkerSize',8, ...
        'MarkerFaceColor','w');

    % ===================== 标准线 =====================
    if ~isnan(standardValues(i))

        yline(standardValues(i), 'k--', ...
            'LineWidth',1.5);

    end

    xticks(1:6);

    xticklabels(modelParams);

    ylabel(yLabels{i}, ...
        'FontSize',FONT_SIZE_LABEL, ...
        'FontName',FONT_NAME);

    title(subTitleList{i}, ...
        'FontSize',FONT_SIZE_TITLE, ...
        'FontWeight','normal', ...
        'FontName',FONT_NAME);

    % ===================== 纵轴范围 =====================
    if i == 1
        ylim([2100 2250]);
    elseif i == 2
        ylim([-1 1]);
    elseif i == 3
        ylim([280 460]);
    end

    set(gca, ...
        'FontName',FONT_NAME, ...
        'FontSize',12, ...
        'LineWidth',1);

    grid on;
    box on;

    % ===================== 图例 =====================
    if i == 1

        legend({'Ellipse model', ...
                'Nonelliptical model', ...
                'Standard value'}, ...
            'Location','best', ...
            'FontSize',FONT_SIZE_LEGEND, ...
            'FontName',FONT_NAME);

    end

end